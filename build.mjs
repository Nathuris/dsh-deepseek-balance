#!/usr/bin/env node
/**
 * Build client.js from the readable sources.
 *
 * The browser half is one self-contained bundle: the module system hands it a
 * factory, and everything it needs (React, ReactDOM, the slot registry) is
 * either a baseline module or an injected service. Sources stay ordinary ESM
 * so `node --test` can import the pure logic directly; this script only strips
 * the module syntax and embeds the bodies inside the factory.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const read = (path) => readFileSync(join(root, path), "utf8");

const stripModuleSyntax = (source) =>
  source
    .replace(/import\s*\{[^}]*\}\s*from\s*["'][^"']+["'];?/g, "")
    .replace(/^export\s+/gm, "");

const indent = (text, pad) =>
  text
    .split("\n")
    .map((line) => (line === "" ? line : pad + line))
    .join("\n");

const logic = stripModuleSyntax(read("src/logic.js"));
const store = stripModuleSyntax(read("src/store.js"));
const chip = stripModuleSyntax(read("src/chip.js"));
const entry = stripModuleSyntax(read("src/index.js"));

const client = `/* dsh-deepseek-balance — client half. GENERATED by build.mjs from src/*.js.
 * Do not edit by hand; run \`npm run build\`.
 */
window.__ModuleLoader__.load({
  id: "dsh-deepseek-balance",
  factory(require) {
    "use strict";
    var React = require("react");
    var ReactDOM = require("react-dom");

${indent(logic, "    ")}

${indent(store, "    ")}

${indent(chip, "    ")}

${indent(entry, "    ")}

    return { inject: inject, apply: apply };
  },
});
`;

writeFileSync(join(root, "client.js"), client);
execFileSync(process.execPath, ["--check", join(root, "client.js")], { stdio: "inherit" });
console.log(`client.js ${client.length} bytes — syntax OK`);
